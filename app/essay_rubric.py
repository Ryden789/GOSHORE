def normalize_status(raw) -> str:
    """把 AI 返回的各种状态说法归一到 命中 / 部分命中 / 缺失。"""
    s = str(raw or "").strip()
    if not s:
        return "缺失"
    if "部分" in s or "半" in s or "🟡" in s:
        return "部分命中"
    if any(k in s for k in ("未", "缺", "漏", "无", "错", "否", "❌", "✗", "×")):
        return "缺失"
    if any(k in s for k in ("命中", "覆盖", "符合", "有", "是", "✅", "✓", "√")):
        return "命中"
    return "缺失"


