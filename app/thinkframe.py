_ORDER = (
    _ZONGYING + _SHENLUN + _SPEECH + _LOGIC + [_QUANT, _DATACALC, _COMMON]
)


def _match(frame: dict, text: str) -> bool:
    if not re.search(frame["pat"], text):
        return False
    need = frame.get("need")
    if need and not re.search(need, text):
        return False
    return True


def analyze(text: str) -> dict | None:
    """按文本命中一个题型框架；命中不了返回 None。"""
    if not text or len(text) < 2:
        return None
    for frame in _ORDER:
        if _match(frame, text):
            block = [f"【题型思考框架·{frame['name']}（本机资料提炼，可直接执行）】"]
            for i, step in enumerate(frame["steps"], 1):
                block.append(f"{i}. {step}")
            block.append(f"易错点：{frame['traps']}")
            block.append(f"出处：{frame['source']}")
            return {
                "name": frame["name"],
                "key": frame["key"],
                "text": "\n".join(block),
                "source": frame["source"],
            }
    return None
